#!/usr/bin/env python3
"""Export CPC18 results to the mlv-tools website raw_data format.

Reads the analysis CSVs written by `src/09_export_csv.py` and writes five
data files the web tools consume:

  cpc18_mse_data_raw.yaml            per-model repeated-run scores (replication /
                                     standardizing tools), 6 models x 800 seeds.
  cpc18_ablation_b1_table.csv        BourginMLP batch_size x learning_rate factorial.
  cpc18_ablation_b3_table.csv        SparseMLP epsilon x learning_rate factorial.
  cpc18_variance_decomposition.json  init x order factorial: variance split,
                                     slicing sigmas and 35x35 grid per neural model.
  cpc18_decomp_mse_data_raw.yaml     the 1225 factorial runs of each neural model.

Directionality: CPC18's metric (mse_x100) is lower-is-better. The first four
files keep its natural POSITIVE values; the web tool flags the metric as
lowerIsBetter and the shared comparison core negates internally only at the
simulation boundary (display stays positive). The exception is
cpc18_decomp_mse_data_raw.yaml, whose values are written negated (see
export_decomposition).

Run from the repo root:
    python scripts/export_web_data.py --out-dir <mlv-tools>/raw_data
"""
import argparse
import csv
import os

import numpy as np

CSV_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "analysis_results", "csv")

# Best-run (ascending min mse) leaderboard order; defines YAML display order.
MODEL_ORDER = ["BEAST_GB", "BourginMLP", "ContextDepNet",
               "SparseMLP", "PsychForest", "LinearLogistic"]


def _read(path):
    with open(path, newline="") as fh:
        return list(csv.DictReader(fh))


def export_mse_yaml(out_dir):
    rows = _read(os.path.join(CSV_DIR, "results_sharedpool_r2.csv"))
    by_model = {}
    for r in rows:
        by_model.setdefault(r["model"], []).append(round(float(r["mse_x100"]), 6))

    order = [m for m in MODEL_ORDER if m in by_model]
    order += [m for m in by_model if m not in order]  # any extras, stable

    out = os.path.join(out_dir, "cpc18_mse_data_raw.yaml")
    with open(out, "w") as fh:
        fh.write("# CPC18 per-model repeated-run scores (mse_x100, lower is "
                 "better). 6 models x 800 seeds.\n")
        fh.write("# Generated by scripts/export_web_data.py - do not edit by hand.\n")
        for m in order:
            vals = by_model[m]
            fh.write("%s: [%s]\n" % (m, ", ".join(repr(v) for v in vals)))
    return out, {m: len(by_model[m]) for m in order}


def export_ablation(out_dir, src_name, dst_name, factor_cols):
    rows = _read(os.path.join(CSV_DIR, src_name))
    # Same seed across all conditions (shared_pool) -> group index by seed rank.
    seeds = sorted({int(r["seed"]) for r in rows})
    seed_index = {s: i for i, s in enumerate(seeds)}

    out = os.path.join(out_dir, dst_name)
    header = ["index", "seed"] + factor_cols + ["mse_x100"]
    with open(out, "w", newline="") as fh:
        w = csv.writer(fh)
        w.writerow(header)
        for r in rows:
            w.writerow([seed_index[int(r["seed"])], r["seed"]]
                       + [r[c] for c in factor_cols]
                       + [round(float(r["mse_x100"]), 6)])
    return out, len(rows), len(seeds)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", required=True,
                    help="raw_data directory of a mlv-tools checkout")
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    y, counts = export_mse_yaml(args.out_dir)
    print("wrote %s  (%s)" % (y, ", ".join("%s=%d" % (m, n) for m, n in counts.items())))

    b1, n1, s1 = export_ablation(args.out_dir, "results_ablation_b1.csv",
                                 "cpc18_ablation_b1_table.csv",
                                 ["batch_size", "learning_rate"])
    print("wrote %s  (%d rows, %d seeds)" % (b1, n1, s1))

    b3, n3, s3 = export_ablation(args.out_dir, "results_ablation_b3.csv",
                                 "cpc18_ablation_b3_table.csv",
                                 ["epsilon", "learning_rate"])
    print("wrote %s  (%d rows, %d seeds)" % (b3, n3, s3))

    d = export_decomposition(args.out_dir)
    print("wrote %s" % d)


def export_decomposition(out_dir):
    """Init x order variance decomposition (Phase C, the 35x35 factorial).

    Emits, per neural model: the variance split (init / order / interaction %,
    a 2-way ANOVA-style SS decomposition read descriptively; one observation
    per cell, but deterministic, so the residual IS exactly the interaction),
    the per-axis slicing sigmas, and the full 35x35 MSE grid so
    the web can draw a heatmap (init x order, colour = MSE). Display is positive
    mse_x100 (no negation: this view is about the spread, not the leaderboard).
    """
    import csv as _csv
    rows = _read(os.path.join(CSV_DIR, "results_factorial_decomp.csv"))
    # group by model -> {(init,order): mse}
    by_model = {}
    for r in rows:
        by_model.setdefault(r["model"], {})[(int(r["init_seed"]), int(r["order_seed"]))] = float(r["mse_x100"])

    def _std(a):
        a = [float(x) for x in a]
        n = len(a)
        if n < 2:
            return 0.0
        m = sum(a) / n
        return (sum((x - m) ** 2 for x in a) / (n - 1)) ** 0.5

    # Seed pools of the factorial, as in src/03_train_decomp.py: the diagonal pairs init_i with order_i.
    init_pool = [int(s) for s in np.random.default_rng(20260522).integers(0, 2**32, size=35, dtype=np.uint64)]
    order_pool = [int(s) for s in np.random.default_rng(99999777).integers(0, 2**32, size=35, dtype=np.uint64)]

    decomposition, slicing, grids = {}, {}, {}
    for m, cells in by_model.items():
        inits = sorted({i for i, _ in cells})
        orders = sorted({o for _, o in cells})
        G = [[cells[(i, o)] for o in orders] for i in inits]  # rows=init, cols=order
        flat = [v for row in G for v in row]
        gm = sum(flat) / len(flat)
        sstot = sum((v - gm) ** 2 for v in flat)
        init_means = [sum(row) / len(row) for row in G]
        order_means = [sum(G[i][j] for i in range(len(inits))) / len(inits) for j in range(len(orders))]
        ss_init = len(orders) * sum((im - gm) ** 2 for im in init_means)
        ss_order = len(inits) * sum((om - gm) ** 2 for om in order_means)
        ss_resid = sstot - ss_init - ss_order
        decomposition[m] = {
            "init": round(100 * ss_init / sstot, 1),
            "order": round(100 * ss_order / sstot, 1),
            "interaction": round(100 * ss_resid / sstot, 1),
        }
        slicing[m] = {
            "init_only": round(sum(_std([G[i][j] for i in range(len(inits))]) for j in range(len(orders))) / len(orders), 3),
            "order_only": round(sum(_std(G[i]) for i in range(len(inits))) / len(inits), 3),
            "init_mean": round(_std(init_means), 3),
            "order_mean": round(_std(order_means), 3),
            "diagonal": round(_std([cells[pair] for pair in zip(init_pool, order_pool)]), 3),
            "full": round(_std(flat), 3),
        }
        grids[m] = [[round(v, 4) for v in row] for row in G]

    order = sorted(decomposition, key=lambda m: -decomposition[m]["interaction"])
    out = os.path.join(out_dir, "cpc18_variance_decomposition.json")
    import json as _json
    with open(out, "w") as fh:
        _json.dump({
            "grid_size": len(next(iter(grids.values()))),
            "metric": "mse_x100",
            "models": order,
            "decomposition": decomposition,
            "slicing": slicing,
            "grids": grids,
        }, fh, separators=(",", ":"))

    # Per-model flattened 35x35 = 1225 runs, negated (lowerIsBetter) so the
    # standard histogram / model-summary / misranking widgets work on the
    # init x order distribution exactly like the main preset.
    yml = os.path.join(out_dir, "cpc18_decomp_mse_data_raw.yaml")
    with open(yml, "w") as fh:
        fh.write("# CPC18 init x order factorial runs (negated mse_x100). "
                 "4 NN models x 1225 (35x35) runs.\n")
        fh.write("# Generated by scripts/export_web_data.py - do not edit by hand.\n")
        for m in order:
            vals = [round(-v, 6) for row in grids[m] for v in row]
            fh.write("%s: [%s]\n" % (m, ", ".join(repr(v) for v in vals)))
    return out


if __name__ == "__main__":
    main()
